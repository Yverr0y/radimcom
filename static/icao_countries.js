/** Hex ICAO address ("4BCCAE") -> {cc, name} or null (the most specific block wins). */
function icaoCountry(hex) {
  const a = parseInt(hex, 16);
  if (!/^[0-9A-Fa-f]{6}$/.test(hex || "") || isNaN(a)) return null;
  let best = null;
  for (const r of ICAO_COUNTRIES) {
    if (a >= r[0] && a <= r[1] && (!best || r[1] - r[0] < best[1] - best[0])) best = r;
  }
  return best ? { cc: best[2], name: best[3] } : null;
}
